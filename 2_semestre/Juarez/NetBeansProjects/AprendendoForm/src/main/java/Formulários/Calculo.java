    private void btn_SomaActionPerformed(java.awt.event.ActionEvent evt) {                                         
        try {
            double x = Double.parseDouble(txt_n1.getText());
            double y = Double.parseDouble(txt_n2.getText());
            double z = x + y;
            txt_res.setText(String.valueOf(z));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, digite apenas números válidos.");
        }
    }                                        

    private void btn_SubActionPerformed(java.awt.event.ActionEvent evt) {                                        
        try {
            double x = Double.parseDouble(txt_n1.getText());
            double y = Double.parseDouble(txt_n2.getText());
            double z = x - y;
            txt_res.setText(String.valueOf(z));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, digite apenas números válidos.");
        }
    }                                       

    private void btn_MultActionPerformed(java.awt.event.ActionEvent evt) {                                         
        try {
            double x = Double.parseDouble(txt_n1.getText());
            double y = Double.parseDouble(txt_n2.getText());
            double z = x * y;
            txt_res.setText(String.valueOf(z));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, digite apenas números válidos.");
        }
    }                                        

    private void btn_DivActionPerformed(java.awt.event.ActionEvent evt) {                                        
        try {
            double x = Double.parseDouble(txt_n1.getText());
            double y = Double.parseDouble(txt_n2.getText());
            
            if (y == 0) {
                txt_res.setText("Não dividir por zero");
            } else {
                double z = x / y;
                txt_res.setText(String.valueOf(z));
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Por favor, digite apenas números válidos.");
        }
    }                                       

    private void btn_RetornarActionPerformed(java.awt.event.ActionEvent evt) {                                             
        // Como não temos outra tela (Abertura), o botão Retornar apenas fecha a calculadora.
        // Se você criar a tela Abertura, descomente as linhas abaixo e apague o dispose() sozinho.
        
        // Abertura tela = new Abertura();
        // tela.setVisible(true);
        dispose(); 
    }                                            

    private void btn_NovoActionPerformed(java.awt.event.ActionEvent evt) {                                         
        txt_n1.setText("");
        txt_n2.setText("");
        txt_res.setText("");
        Habilitar();
        txt_n1.requestFocus(); // Coloca o cursor piscando no N1
    }                                        

    private void btn_LimparActionPerformed(java.awt.event.ActionEvent evt) {                                           
        txt_n1.setText("");
        txt_n2.setText("");
        txt_res.setText("");
        txt_n1.requestFocus();
    }                                          

    private void btn_SairActionPerformed(java.awt.event.ActionEvent evt) {                                         
        System.exit(0);
    }                                        

